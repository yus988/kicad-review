const LANG = /^ja\b/i.test(document.documentElement.lang || '') ? 'ja' : 'en';

function t(key, vars) {
  let s = I18N[LANG][key];
  if (s == null) s = I18N.en[key];
  if (s == null) { console.warn('kicad-review: no text for', key); return key; }
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : s;
}

// the static text of the page
function applyI18n(root) {
  const box = root || document;
  box.querySelectorAll('[data-i18n]').forEach(e => { e.textContent = t(e.dataset.i18n); });
  box.querySelectorAll('[data-i18n-title]').forEach(e => { e.title = t(e.dataset.i18nTitle); });
  box.querySelectorAll('[data-i18n-placeholder]').forEach(e => { e.placeholder = t(e.dataset.i18nPlaceholder); });
}
